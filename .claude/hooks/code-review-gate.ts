#!/usr/bin/env bun
/**
 * Code review gate — one script for two hook events.
 *
 * - `UserPromptSubmit`: records a per-path fingerprint of the dirty working tree (`path → sha256`) for this
 *   session. Writes nothing to stdout — that would be injected into the prompt.
 * - `Stop`: compares the tree with that fingerprint. If this turn changed non-doc files and no
 *   `review-changes` subagent has started since the last user turn, it blocks the stop and tells the main
 *   agent to run the `review` skill, naming the changed files (the allowed apply set in `review.md`).
 *
 * A fingerprint instead of Edit/Write paths from the transcript, because Bash-made changes (codegen, `rm`,
 * `git mv`, sed edits) never show up as Edit/Write inputs.
 *
 * **Fail open.** Any error, a missing snapshot or a tree above the size bounds ends in exit 0 with no stdout —
 * a broken gate must never keep the agent from ending its turn. `stop_hook_active` lets the stop through after
 * one block, so the gate cannot loop.
 *
 * Debug: `CODE_REVIEW_GATE_DEBUG=/path/dump.jsonl` appends each payload plus the decision.
 */
import { appendFileSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { z } from 'zod';

import { git } from '../../scripts/privacy-scan';
import { readHookInput, runFailOpen } from './hook-runtime';
import { isAgentStart, lastUserTurnIndex } from './plan-review-round';
import { type TranscriptLine, parseTranscript } from './plan-review-transcript';

const REVIEW_AGENT = 'review-changes';
/**
 * Never reviewed, on purpose: `corpus/` is fetched data — listed here because it is not yet in `.gitignore` (M6
 * adds it) and thousands of untracked files would blow the hook timeout; `results/` is committed but generated by
 * the experiment runner (README numbers come from it), so its code is what gets reviewed, not its output.
 */
const IGNORED_DIRS = ['corpus/', 'results/'];
const DELETED = 'deleted';
const SAFE_SESSION_ID = /^[A-Za-z0-9_-]+$/;

export interface Limits {
  maxFiles: number;
  maxBytes: number;
}

/** Above these the snapshot is skipped and the gate fails open — keeps the hook well inside its timeout. */
const DEFAULT_LIMITS: Limits = { maxFiles: 500, maxBytes: 20 * 1024 * 1024 };

export type Snapshot = Record<string, string>;

const snapshotSchema = z.record(z.string(), z.string());

const hookInputSchema = z.object({
  hook_event_name: z.string().optional(),
  session_id: z.string().optional(),
  transcript_path: z.string().optional(),
  cwd: z.string().optional(),
  agent_id: z.string().optional(),
  stop_hook_active: z.boolean().optional(),
});

type HookInput = z.infer<typeof hookInputSchema>;

type Decision = { kind: 'skip' } | { kind: 'block'; reason: string };

/** Paths from `git status --porcelain -z`; a rename/copy entry is followed by its source path. */
export function parsePorcelain(output: string): string[] {
  const tokens = output.split('\0');
  const paths: string[] = [];

  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];

    if (token === undefined || token.length < 4) {
      continue;
    }

    paths.push(token.slice(3));

    if (token[0] === 'R' || token[0] === 'C') {
      const source = tokens[i + 1];

      if (source !== undefined && source.length > 0) {
        paths.push(source);
      }

      i++;
    }
  }

  return paths;
}

/** Fingerprint of every dirty path under `root`, or `null` when the tree exceeds the limits. */
export function snapshot(root: string, limits: Limits = DEFAULT_LIMITS): Snapshot | null {
  const status = git(['-C', root, 'status', '--porcelain', '-uall', '-z']).toString('utf8');
  const paths = parsePorcelain(status).filter((p) => !IGNORED_DIRS.some((dir) => p.startsWith(dir)));

  if (paths.length > limits.maxFiles) {
    return null;
  }

  const result: Snapshot = {};
  let bytes = 0;

  for (const path of paths) {
    const full = join(root, path);
    const stats = statSync(full, { throwIfNoEntry: false });

    if (stats === undefined || !stats.isFile()) {
      result[path] = DELETED;
      continue;
    }

    bytes += stats.size;

    if (bytes > limits.maxBytes) {
      return null;
    }

    result[path] = new Bun.CryptoHasher('sha256').update(readFileSync(full)).digest('hex');
  }

  return result;
}

/** Paths that were added, changed or removed between two snapshots, sorted. */
export function changedPaths(before: Snapshot, after: Snapshot): string[] {
  const keys = new Set([...Object.keys(before), ...Object.keys(after)]);

  return [...keys].filter((key) => before[key] !== after[key]).sort();
}

/** Plain docs only. `.claude/**` and any `CLAUDE.md` hold agent rules and do get reviewed. */
export function isDocOnly(paths: string[]): boolean {
  return paths.every((path) => {
    const segments = path.split('/');

    return path.endsWith('.md') && !segments.includes('.claude') && segments.at(-1) !== 'CLAUDE.md';
  });
}

function blockReason(paths: string[]): string {
  return (
    'This turn changed code and has not been reviewed. Run the `review` skill (`/review`) now. ' +
    `Files changed this turn: ${paths.join(', ')}`
  );
}

/** `changed` is `null` when no comparison was possible (missing snapshot, limits exceeded). */
function isReviewable(changed: string[] | null): changed is string[] {
  return changed !== null && changed.length > 0 && !isDocOnly(changed);
}

export function decide(input: HookInput, lines: TranscriptLine[], changed: string[] | null): Decision {
  if (input.agent_id !== undefined || input.stop_hook_active === true) {
    return { kind: 'skip' };
  }

  if (!isReviewable(changed)) {
    return { kind: 'skip' };
  }

  const anchor = lastUserTurnIndex(lines);

  if (lines.slice(anchor + 1).some((line) => isAgentStart(line, REVIEW_AGENT))) {
    return { kind: 'skip' };
  }

  return { kind: 'block', reason: blockReason(changed) };
}

function snapshotFile(sessionId: string): string {
  return join(tmpdir(), 'claude-code-review', sessionId);
}

/**
 * Removes the previous snapshot first: a stale one must never be compared against. One small file per session
 * stays in the temp dir afterwards — accepted, the OS cleans it up.
 */
export function recordSnapshot(root: string, file: string, limits: Limits = DEFAULT_LIMITS): void {
  rmSync(file, { force: true });
  const snap = snapshot(root, limits);

  if (snap === null) {
    return;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(snap));
}

function readSnapshot(file: string): Snapshot | null {
  const stats = statSync(file, { throwIfNoEntry: false });

  if (stats === undefined) {
    return null;
  }

  return snapshotSchema.parse(JSON.parse(readFileSync(file, 'utf8')));
}

async function main(): Promise<void> {
  const { stdin, debug } = await readHookInput('CODE_REVIEW_GATE_DEBUG');
  const input = hookInputSchema.parse(JSON.parse(stdin));
  const root = process.env.CLAUDE_PROJECT_DIR ?? input.cwd;
  const sessionId = input.session_id;

  if (root === undefined || sessionId === undefined || !SAFE_SESSION_ID.test(sessionId)) {
    return;
  }

  const file = snapshotFile(sessionId);

  if (input.hook_event_name === 'UserPromptSubmit') {
    recordSnapshot(root, file);
    return;
  }

  if (input.hook_event_name !== 'Stop' || input.transcript_path === undefined) {
    return;
  }

  const before = readSnapshot(file);
  const after = before === null ? null : snapshot(root);
  const changed = before === null || after === null ? null : changedPaths(before, after);
  // Only read the (growing) transcript when there is something to review.
  const lines = isReviewable(changed) ? parseTranscript(await Bun.file(input.transcript_path).text()) : [];
  const decision = decide(input, lines, changed);

  if (debug !== null) {
    appendFileSync(debug, `${JSON.stringify({ decision, changed })}\n`);
  }

  if (decision.kind === 'block') {
    process.stdout.write(`${JSON.stringify({ decision: 'block', reason: decision.reason })}\n`);
  }
}

if (import.meta.main) {
  // Fail open: a skipped review beats an agent that cannot end its turn.
  await runFailOpen('code-review-gate', main);
}
